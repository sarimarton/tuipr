//
// What lives here: the attestation review body and attribution parsing, the
// session probe / wait / reload, comment reading with the MEASURED (b) schema,
// the "no active session" SEPARATE error class, opening the review view (the
// wf26 TTY-fd pattern!), reinjecting findings, and the GitHub upload.
//
