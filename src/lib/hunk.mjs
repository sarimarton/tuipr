/**
 * The argv for querying SESSION EXISTENCE.
 *
 * `session list --json` is the SEMANTICALLY correct question: "which active
 * sessions are there?". That's a DIFFERENT question from `comment list`
 * ("what are the findings?") — and separating the two is LOAD-BEARING:
 *
 *   - the session PROBE is the PRECONDITION for starting claude (order
 *     guarantee),
 *   - `comment list` is the `before`/`after` MEASUREMENT.
 *
 * A MEASURED CONSEQUENCE (caught by mutation testing): as long as the probe
 * also ran on `comment list`, the two steps merged UNOBSERVABLY — the order
 * guarantee could be removed without any test going red, because throwing the
 * `before` measurement MASKED the missing wait.
 *
 * NO `--repo` FLAG (MEASURED, hunk 0.17.0):
 *   $ hunk session list --repo /x  →  "error: unknown option '--repo'", exit 1
 * The options are: `--json` and `-h`. So WE do the repo filtering on the
 * JSON — assuming a `--repo` flag here would have given a SILENT exit-1,
 * which the three-state detection (empty stdout + non-zero exit) read as "no
 * session": the TUI would open a new one on every probe.
 */
export function hunkSessionListCommand() {
  return ['session', 'list', '--json']
}

/**
 * Is there an ACTIVE hunk session FOR THIS REPO? — THREE STATES (see
 * `hunkSessionAlive`).
 *
 * SIDE-EFFECT-FREE: `session list` only ASKS (a `reload` would MODIFY, a
 * `diff` would OPEN A NEW ONE — a state query must not do that).
 *
 * THE FILTER GOES ON MATCHING `repoRoot`, because `session list` lists EVERY
 * session — including ones opened for other repos. An unfiltered "there's at
 * least one session" answer would reproduce exactly the user-reported bug:
 * for them the ONE registered session pointed at an ALREADY DELETED temp
 * directory (`/private/var/…/tmp.G4I6zLIvk5/probe`), and there was none for
 * the mobile repo — an unfiltered probe would still have reported an "active
 * session".
 *
 * THE MEASURED JSON SCHEMA (hunk 0.17.0): `{ sessions: [{ sessionId, pid,
 * cwd, repoRoot, … }] }`. `repoRoot` is the anchor, NOT `cwd`: `cwd` is where
 * it was launched from (can also be a subdirectory within the repo), whereas
 * `repoRoot` is the same root that `comment list --repo` expects.
 */
export function probeHunkSession(repoRoot) {
  const res = spawnSync(hunkBin(), hunkSessionListCommand(), { encoding: 'utf8' })
  // A MISSING BINARY / spawn error is NOT a session state (see hunkSessionAlive).
  if (res.error) return null
  if (res.status !== 0) return hunkSessionAlive(res)
  let env
  try {
    env = JSON.parse(res.stdout || '')
  } catch {
    // THE CONTRACT FAILED: from unparseable output we infer NEITHER existence
    // NOR absence. The `null` gives the caller the raw error — a "no session"
    // guess here would open a new hunk on every probe.
    return null
  }
  if (!env || !Array.isArray(env.sessions)) return null
  // THE COMPARISON runs on the RAW roots. hunk gives the realpath'd form
  // (`/private/var/…`), and the caller also uses `git rev-parse
  // --show-toplevel`'s realpath'd root: so the two forms match.
  return env.sessions.some((s) => s?.repoRoot === repoRoot)
}

/**
 * The IDENTIFIER of the repo root's ACTIVE hunk session — the load-guard's
 * anchor.
 *
 * WHY IT'S NEEDED (the user's 5th run, 3rd finding): the `applied` flag on
 * its own is only tied to the PR, but hunk's `q` also TAKES THE SESSION WITH
 * IT — reopening gets a NEW, EMPTY session, where the loaded notes AREN'T
 * there. So the guard has to know WHERE the load happened: `sessionId` is
 * part of the MEASURED schema (`session list --json` →
 * `sessions[].sessionId`, hunk 0.17.0).
 *
 * `null` on EVERY non-measurable branch (error / garbage output / no match):
 * the caller (answerFindingsNeedApply) makes a fail-safe decision from that —
 * `null` never matches an active identifier, so it behaves as "no
 * identifiable active session". It does NOT throw: identifier reading is a
 * cosmetic path alongside the opening, a throw here would take down the
 * whole opening.
 */
export function hunkLiveSessionId(repoRoot) {
  const res = spawnSync(hunkBin(), hunkSessionListCommand(), { encoding: 'utf8' })
  if (res.error || res.status !== 0) return null
  let env
  try {
    env = JSON.parse(res.stdout || '')
  } catch {
    return null
  }
  if (!env || !Array.isArray(env.sessions)) return null
  const own = env.sessions.find((s) => s?.repoRoot === repoRoot)
  const sid = own?.sessionId
  return typeof sid === 'string' && sid !== '' ? sid : null
}

/**
 * THE BACKGROUND REVIEW'S ORDER GUARANTEE: waiting until the session APPEARS.
 *
 * WHY IT'S NEEDED (a requirement of the parallel model (i)): `claude` can
 * ONLY start once the session ALREADY exists — otherwise exactly the same
 * "no active session" error comes back, just IN THE BACKGROUND, and the
 * token is ALREADY spent for nothing. `hunk diff`, though, starts an
 * INTERACTIVE TUI in a SEPARATE process: the session isn't created at the
 * moment of spawn, but when hunk's daemon registers it. This has to be
 * MEASURED, not assumed.
 *
 * THE WAIT polls with EXPONENTIAL BACKOFF (50 → 100 → 200 → … ms), and GIVES
 * UP after `timeoutMs`. The giveup is LOUD: it returns `false`, and the
 * caller does NOT start claude. Silently proceeding here would spend a token
 * on a session that doesn't exist.
 *
 * `sleep` and `now` are INJECTABLE: without that the timeout branch's test
 * would take real seconds (or — worse — be flaky).
 */
export async function waitForHunkSession(repoRoot, {
  timeoutMs = 10_000,
  probe = probeHunkSession,
  sleep = (ms) => new Promise((r) => setTimeout(r, ms)),
  now = () => Date.now(),
} = {}) {
  const started = now()
  let delay = 50
  for (;;) {
    const alive = probe(repoRoot)
    // `true` — got it. `null` — NOT KNOWABLE (daemon error / missing binary):
    // waiting here has NO point, the error isn't about timing. The caller
    // gives the raw diagnosis instead of waiting 10 seconds for an
    // installation error.
    if (alive === true) return true
    if (alive === null) return null
    if (now() - started >= timeoutMs) return false
    await sleep(delay)
    delay = Math.min(delay * 2, 1000)
  }
}

/**
 * The `noteId` SET OF THE AGENT FINDINGS IN THE SESSION.
 *
 * WHY A SET AND NOT A COUNT (a requirement of the parallel model (ii)): in
 * the synchronous model, a `before`/`after` COUNT was enough, because while
 * claude ran NOBODY ELSE could write to the session. In the parallel model
 * the USER ALSO writes — they sit in the diff while the agent works. A mere
 * increment therefore does NOT prove that the AGENT wrote anything: with two
 * user comments the gate would still claim "successful review" even if
 * claude wrote not a single line.
 *
 * THE SET DIFF stays CORRECT even with user writes: it gives exactly the IDs
 * that appeared WHILE claude was running.
 *
 * A MEASURED FACT (hunk 0.17.0, in a live TUI, driven from tmux — the
 * separation is RELIABLE, so the `--type agent` filter alone would already be
 * fine; the set diff is the SECOND line of defense):
 *   - a comment written BY HAND (`c`) in the hunk TUI: `source: "user"`,
 *     `noteId: "user:<epoch-ms>"` — `--type agent` gives an EMPTY list for
 *     this;
 *   - one written via the CLI (`comment apply`): `source: "agent"`,
 *     `noteId: "mcp:<uuid>:<n>"` — `--type user` gives an empty list for this.
 * So the two never blur together; but the set diff stays correct even if a
 * future hunk version changes this.
 */
export function hunkAgentNoteIds(repoRoot, opts) {
  return new Set(hunkComments(repoRoot, opts).map((c) => c.noteId).filter((id) => id !== undefined))
}

/**
 * SWITCHING the EXISTING session to the PR's diff — the core of the
 * SINGLETON behavior.
 *
 * Returns `true` if the reload SUCCEEDED (so NO new session needs opening).
 * `false` if there's nothing to reload (no active / an ORPHANED session) —
 * the caller OPENS one in that case. This fail-soft branch is DELIBERATE:
 * the user ran into exactly the orphaned-session case (a deleted temp root),
 * and throwing there would have been a dead end.
 *
 * THROWS on any OTHER, NAMED hunk error: a false "no session" diagnosis
 * would start a SECOND hunk for the same underlying problem (daemon crash,
 * locked DB).
 */
export function reloadHunkSession(repoRoot, base, head) {
  const res = spawnSync(hunkBin(), hunkSessionReloadCommand(repoRoot, base, head), { encoding: 'utf8' })
  const alive = hunkSessionAlive(res)
  if (alive === true) return true
  if (alive === false) return false
  // `null` — NOT KNOWABLE. A missing binary is a SEPARATE diagnosis (same
  // principle as hunkComments's ENOENT branch): there the problem isn't the
  // session.
  if (res.error?.code === 'ENOENT') {
    throw new Error(
      'the `hunk` binary is not launchable — neither core\'s bundled instance '
      + '(`node_modules/.bin/hunk`, the `hunkdiff` dependency), nor one on PATH. '
      + 'Run `pnpm install` in core. That\'s why the review session can\'t be '
      + 'managed. This is NOT a session error: the binary itself is missing.\n'
      + 'What to do: `brew install hunk` (installs it/puts it on PATH), then try again.',
    )
  }
  const spawnErr = spawnFailure(res, 'hunk')
  if (spawnErr) throw new Error(`the hunk session can't be switched over: ${spawnErr}`)
  throw new Error(
    `switching the hunk session over did not succeed (session reload, exit ${res.status}): `
    + `${(res.stderr || res.stdout || '').trim() || '(no output)'}`,
  )
}




/**
 * Opening the review diff in hunk. Configurable: TUIPR_REVIEW_CMD — the
 * {base}, {head}, {pr} placeholders get substituted.
 *
 * Default: fetching the PR branch into a local ref, then `hunk diff
 * base...head`. This triple-dot form computes from the MERGE BASE, so it
 * gives the same diff that GitHub shows — and hunk's line anchors are the
 * post-image line numbers, which toGithubComments maps directly onto
 * GitHub's RIGHT side.
 */
/**
 * (wf31/19) THE CHILD RUNS IN ITS OWN PTY — via `script(1)`.
 *
 * THE HANG'S ROOT CAUSE, MEASURED ON THREE LIVE INCIDENTS (`ps -o pgid` +
 * `lsof` on the stuck state): hunk and the TUI sat in the SAME process group,
 * and the terminal's foreground pgrp WAS that group — so the KERNEL ALLOWED
 * BOTH to read the TTY. The parent absorbed the keystrokes, hunk sat waiting
 * for input in `S+`, and never got a keypress. From there the chain: it
 * doesn't exit → `close` doesn't fire → `finally` doesn't run → the fds stay
 * open too (the measured stuck state had SIX TTY descriptors on the parent,
 * from repeated `d` openings).
 *
 * THE DECISIVE OBSERVATION: the child HAD its own `/dev/tty` fd (`0r`, the
 * wf26 fix), and STILL got stuck. The kernel decides based on the PGRP, not
 * the fd — so both the fd swap (wf26) and `process.stdin.pause()` (wf31/18)
 * were attacking the WRONG LEVEL. Both were MEASURABLY insufficient: the
 * third hang happened with that fix already in the code.
 *
 * WHAT I ALSO RULED OUT, BY MEASUREMENT: `bash -mc` (job control). In `-m
 * -c` mode it does NOT put things into a separate process group — the
 * child's pgid stays the same as the parent's (measured: 41193 in both
 * forms). The assumption was wrong.
 *
 * `script -q /dev/null`, though, gives the child its OWN PSEUDOTERMINAL, and
 * makes it a process group leader (measured: `pgid == pid`,
 * `tty=/dev/ttysNNN` — DIFFERENT from the parent's terminal). The contention
 * thus disappears IN PRINCIPLE: hunk reads its own PTY, the parent reads its
 * own — no shared descriptor, no shared pgrp.
 *
 * `-q` suppresses `script`'s header/footer ("Script started/done on …"),
 * which would otherwise write into the TUI's picture. `/dev/null` is the
 * typical scriptfile stand-in: `script` ALWAYS logs, but we throw it away
 * here.
 *
 * PASSING THE TERMINAL SIZE IS A REQUIREMENT, NOT A NICETY: `script`'s PTY
 * gets a DEFAULT size, not the real terminal's — measured, it even gave `0
 * 0`. At the wrong width the hunk TUI wraps/truncates. So the child's shell
 * FIRST sets the MEASURED size via `stty` (and turns off echo — see there),
 * and only then starts hunk. The size is the value valid AT THE MOMENT OF
 * SPAWN (the caller passes it in) — a resize AFTER the spawn isn't tracked,
 * which is a KNOWN LIMITATION: hunk stays at that same size until `q`. (The
 * user's feedback: "hunk doesn't resize with the terminal window, but that's
 * something we can live with.")
 */
function ptyWrap(inner, { columns, rows }) {
  // THE SIZE PREFIX ONLY GOES IN WITH A MEASURED VALUE: a made-up `80 24`
  // would be worse than `script`'s default, because it gives FALSE precision.
  // On a non-TTY (pipe, test) the caller gives `null`, and then the `stty`
  // is left out too.
  //
  // (wf31/20) `-echo` GOES IN TOO: `script`'s PTY starts with DEFAULT ECHO,
  // and on opening writes a `^D\b\b` to the output (MEASURED: `od -c` on
  // `script -q`'s output — `-q` suppresses the header, but NOT THIS). This
  // litters the TUI's picture/the scrollback. hunk sets its own raw mode
  // anyway, so turning off echo doesn't affect its behavior — it only
  // cleans up the PTY's starting state.
  const sttyArgs = ['-echo']
  if (Number.isInteger(columns) && columns > 0 && Number.isInteger(rows) && rows > 0) {
    sttyArgs.push(`rows ${rows}`, `cols ${columns}`)
  }
  // `exec` IS LOAD-BEARING: without it the shell would STAY ALIVE alongside
  // hunk, so `script`'s child would be a shell, not hunk — and the `close`
  // event would fire when the SHELL (not hunk) exits. `exec` also removes
  // one process from the chain.
  return ['script', ['-q', '/dev/null', 'bash', '-c', `stty ${sttyArgs.join(' ')}; exec ${inner}`]]
}

/**
 * The hunk-diff command's INNER (writable into `bash -c`) form, WITHOUT the
 * `script` wrapper.
 *
 * WHY IT'S SPLIT OUT from `ptyWrap`: the node-pty relay (`openReviewViaPty`,
 * below) ITSELF gives the child its own PTY and its own process group — the
 * `script`-based wrapper (which exists for EXACTLY these two properties, see
 * `ptyWrap`'s header) would be REDUNDANT there. But building the command is
 * IDENTICAL on BOTH paths (the `TUIPR_REVIEW_CMD` template + the default
 * `hunk diff`), so it lives in ONE place — split apart, the template
 * substitution would easily fall behind on one path at some future change.
 */
export function reviewInnerCommand(pr, base, head, { agentNotes = false } = {}) {
  const tpl = process.env.TUIPR_REVIEW_CMD
  if (tpl) {
    // THE TEMPLATE is the user's OWN command — we don't inject a flag into
    // it: they know what they want to run, and a foreign `--agent-notes`
    // could well trip it up.
    return tpl.replaceAll('{pr}', String(pr)).replaceAll('{base}', base).replaceAll('{head}', head)
  }
  // `--agent-notes` is a MEASURED flag (hunk 0.17.0 `diff --help`: "show
  // agent notes by default"): on opening the review (r, and the `d` load
  // path too) the AI comments are IMMEDIATELY visible, no need for the `a`
  // toggle. The pending-free `d` path runs WITHOUT the flag — staying,
  // byte-for-byte, hunk's default.
  return `${hunkBinShell()} diff${agentNotes ? ' --agent-notes' : ''} "${base}...${head}"`
}

export function reviewCommand(pr, base, head, { agentNotes = false, columns = null, rows = null } = {}) {
  // THE PTY WRAPPING IS NEEDED HERE: the hang comes from TTY contention,
  // which is INDEPENDENT of what we run — the user's own template
  // (`TUIPR_REVIEW_CMD`) would get stuck the same way. This path is for the
  // `script`-based (non-node-pty) opening, see `openReviewView`'s call site.
  return ptyWrap(reviewInnerCommand(pr, base, head, { agentNotes }), { columns, rows })
}

/**
 * THE hunk-diff SPAWN OPTIONS — `cwd` gets decided HERE, in ONE place.
 *
 * ROOT CAUSE OF A REAL, USER-REPORTED BUG ("no active session" even after
 * `d`): `openReview` used the `spawnSync(cmd, args, { stdio: 'inherit' })`
 * form **WITHOUT `cwd`**. So hunk saw the TUI PROCESS's working directory as
 * repoRoot, while `hunkComments` queried the `--repo <git rev-parse
 * --show-toplevel>` root. So the session was created against a DIFFERENT
 * root than the one we were looking for — and the two roots only matched
 * when the user happened to launch the TUI from the repo's root.
 *
 * MEASURED ON A TMUX PTY (the TUI launched from a directory OUTSIDE the
 * repo):
 *   hunk diff origin/main...refs/tuipr/pr/101   [cwd=/tmp/tuipr-pty/elsewhere]
 *   hunk session comment list --repo /tmp/tuipr-pty/repo --type agent --json
 *
 * FAIL-SOFT, BUT NOT DISHONEST: if the root isn't measurable (empty/null),
 * `cwd` is LEFT OUT — the process inherits its own, as before. A `cwd: ''`
 * on spawnSync would give DIFFERENT behavior (and `d` would silently fail),
 * while a `cwd: undefined` would suggest false precision at the call site.
 *
 * --- (wf26) STDIO: WHY IT'S NO LONGER `'inherit'` --------------------------
 *
 * A FINDING FROM THE USER'S 6TH LIVE RUN: exiting the hunk view with `q`, the
 * TUI DID NOT COME BACK — the list disappeared, only the header line
 * remained in the shell. The process neither crashed nor exited: it FROZE
 * FOREVER.
 *
 * THE DIAGNOSIS, on a live PTY, measuring the FROZEN process with
 * `sample(1)` — the main thread's native stack at the moment of the hang:
 *
 *   uv_run → uv__io_poll → uv__stream_io → read (libsystem_kernel.dylib)
 *
 * So the loop sits in a BLOCKING `read()` on the TTY (NOT in `kevent`), so it
 * CAN'T EVEN PROCESS the SIGCHLD signaling the child's death: hunk's child
 * turned into a ZOMBIE (`ps`: `ZN+ <defunct>`), `openReviewView`'s promise
 * never settled, and even the `setInterval` timers stopped. So the `d` path
 * NEVER EVEN REACHED the render after resume — the bug is NOT the render,
 * NOT the `loadedAt`-based hiding, and NOT the wf20 async reload.
 *
 * THE CAUSE is `stdio: 'inherit'`: the child got the SAME TTY fd that Node
 * (through Ink's raw-mode stdin) was ALREADY reading from.
 *
 * THE MEASURED ISOLATION (reproduced on a live PTY, without Ink too):
 *   - without stdin reading / only `setRawMode` / only `ref()` → `close` FIRES
 *   - a `readable` listener OR `resume()`                      → HANGS
 *   - `pause()` + `unref()` + `removeAllListeners()` before spawn → HANGS
 *     (the blocking `read()` is ALREADY inside the syscall — not revocable
 *     at the stream level; that's why "pausing" around the call site is NOT
 *     the fix)
 *   - a dedicated `/dev/tty` fd for the child                  → `close` FIRES
 *
 * THE CHILD'S INTERACTIVITY IS NOT AFFECTED (measured in the child on a live
 * PTY: `tty=/dev/tty`, `[ -t 0 ]` = yes, `stty size` = 30 120, keypresses
 * arrive, `q` exits), and the parent RECLAIMS the terminal after closing: the
 * `/dev/tty` is the SAME terminal, just a DIFFERENT fd — that's exactly what
 * resolves the stuck state.
 *
 * `closeFds()` is NOT an optional nicety: `d` runs many times within one
 * session, and with an fd leak the TUI would sooner or later die with EMFILE.
 */
export function reviewSpawnOptions(repoRoot) {
  const root = typeof repoRoot === 'string' ? repoRoot.trim() : ''
  const base = root === '' ? {} : { cwd: root }
  return {
    ...base,
    // (wf31/19) ALL THREE DIRECTIONS `'inherit'` — the dedicated `/dev/tty`
    // fd REMOVED.
    //
    // WHY: the child now runs in its OWN PTY (`script -q /dev/null` — see
    // `reviewCommand`'s header), so its terminal is provided by `script`, not
    // us. A separate `/dev/tty` opening in this model is REDUNDANT (the
    // contention has already been eliminated at the PTY level) and also
    // HARMFUL: `script` wants to bind ITS OWN PTY to the child's stdin, and an
    // explicit fd would override that.
    //
    // WHAT GOES AWAY WITH IT: the fd LEAK. In the measured, stuck state the
    // parent had SIX TTY descriptors (`0u 1u 2u 11u 15u 16u 17r`) —
    // `closeFds()` only ran if the promise settled, and with a hang it
    // didn't. What we don't open, we don't need to close either.
    //
    // WHAT STAYS UNCHANGED: the `[fd, fd, fd]` form CRASHED on Bun's `kqueue`
    // (EINVAL, measured on hunk 0.17.0 / Bun v1.3.14) — that's why we didn't
    // go back to explicit write fds either. `'inherit'` is the measured,
    // working form.
    stdio: 'inherit',
    // `closeFds` STAYS a NO-OP: the call site's `finally` calls it
    // (`spawnOpts.closeFds?.()`), and its contract (idempotent, never throws)
    // is unchanged — there's just nothing left to close.
    closeFds: () => {},
  }
}

// (wf31/19) `defaultOpenTty` REMOVED: the child runs in its own PTY
// (`script -q /dev/null`), so we don't open a `/dev/tty` for it. The
// reasoning is in `reviewSpawnOptions`'s stdio explanation.

/**
 * Opening the hunk-diff view as an ASYNCHRONOUS child — handing over the
 * terminal.
 *
 * WHY NOT `spawnSync` (A MEASURED BUG, observed on a live PTY in tmux):
 * `spawnSync` blocks the NODE EVENT LOOP for the child's WHOLE lifetime. And
 * the hunk TUI runs until the user presses `q` — so with spawnSync,
 * PARALLELISM IS IMPOSSIBLE IN PRINCIPLE: `waitForHunkSession`'s poll NEVER
 * ran again, and `claude` only started AFTER the diff CLOSED. The log showed
 * this: the session was ALREADY alive (`session.alive` existed), yet the wait
 * made no progress, because the loop was stuck.
 *
 * With `spawn` the loop stays free: the session probe runs, claude starts,
 * and the findings appear in the diff that's STILL OPEN — exactly what the
 * user asked for.
 *
 * `stdio: 'inherit'` is UNCHANGED: hunk needs a REAL TTY (interactive TUI).
 * The promise settles when the child EXITS, so the caller can still wait for
 * the view to close — it just doesn't freeze the process meanwhile.
 */
export function openReviewView(cmd, args, opts, {
  spawn: spawnImpl = spawn,
  watchdog = null,
  onExit = null,
} = {}) {
  return new Promise((resolve, reject) => {
    const child = spawnImpl(cmd, args, opts)
    let settled = false
    // `stopWatch`'s DECLARATION BEFORE `done` — `done` reads it through its
    // closure, and a `let` below it would give a TDZ error if `close` fired
    // BEFORE the watchdog was set up (short-lived child: ENOENT, immediate
    // exit).
    let stopWatch = null
    const done = (fn, arg) => {
      if (settled) return
      settled = true
      stopWatch?.()
      fn(arg)
    }
    // (wf31/16) THE STUCK-STATE WATCHDOG — from a live user incident.
    //
    // THE SYMPTOM: `d` opened `hunk diff`, and the WHOLE terminal froze — no
    // mouse, no keyboard, no `Ctrl-C`. The measured state (`ps`/`lsof`): hunk
    // was `S+` (foreground, WAITING FOR INPUT), and held TWO reader fds on
    // the same `/dev/tty`, while the parent Node's libuv was also stuck
    // inside a blocking TTY `read()`. `Ctrl-C` had no effect either: Ink's
    // raw mode turns off `ISIG`, so `^C` turned into a BYTE instead of a
    // signal — going to a reader that didn't process it.
    //
    // WHY "DOES IT WRITE ANYTHING" ISN'T THE SIGNAL: the child's
    // stdout/stderr are INHERITED (`stdio: [fd, 'inherit', 'inherit']` — see
    // `reviewSpawnOptions`'s reasoning), so the parent CANNOT SEE what it
    // writes. Detecting a "gone silent" child is impossible in principle on
    // this path.
    //
    // THE RELIABLE SIGNAL IS THE SESSION APPEARING, measured from ANOTHER
    // process: `hunk session list --json` asks the DAEMON (not the child
    // sitting on the TTY), so it answers even if the child is stuck on the
    // terminal. If hunk starts NORMALLY, the session registers within
    // seconds; if it's stuck on the TTY, NEVER. This is `waitForHunkSession`'s
    // already-proven mechanism — here we just use it for a DIFFERENT purpose
    // (a guard, not an order guarantee).
    //
    // FAIL-SOFT ON EVERY UNCERTAINTY: `watchdog` ONLY kills if the probe gave
    // an EXPLICIT `false` (the daemon answered, and the session ISN'T there).
    // `null` (not measurable: daemon error, missing binary) is NOT a kill —
    // there we don't know what's happening, and cutting off a WORKING diff is
    // worse than waiting. The same doctrine that governs `probeHunkSession`'s
    // `null` branch.
    if (watchdog) stopWatch = watchdog(child, (reason) => done(reject, reason))
    child.on('error', (error) => {
      done(reject, error?.code === 'ENOENT'
        ? new Error(
          `\`${cmd}\` is not launchable (ENOENT): it's not installed, or not on PATH. `
          + 'This is NOT a review error — the binary itself is missing.',
        )
        : new Error(`the diff view could not be launched: ${error?.message ?? String(error)}`))
    })
    // A NON-ZERO EXIT IS NOT AN ERROR: exiting the hunk TUI (`q`) is
    // legitimate, and pager-like tools often return non-zero on interruption.
    // `d`'s contract is that the view CLOSED — not that it did so with 0.
    // (wf31/48) THE `exit` HOOK — A SIGNAL EARLIER THAN `close`, FOR COSMETIC
    // PURPOSES.
    //
    // WHY IT'S NEEDED SEPARATELY FROM `close`: the promise resolves ON
    // `close` (that's the correct contract — by then stdio has closed too),
    // BUT `close`, per measurement, comes ~50 ms AFTER the process's actual
    // exit. hunk, though, writes `?1049l` IMMEDIATELY on exit, so in that
    // window the shell's picture shows through. The caller can step back
    // into the alt screen on this hook as early as possible.
    //
    // PURELY COSMETIC: the hook does NOT settle the promise, and its error
    // doesn't change the outcome either — a throwing hook must not be able to
    // take down the `d` path. That's why it's fail-soft, and why it does NOT
    // go through `done`.
    child.on('exit', () => {
      try {
        onExit?.()
      } catch { /* cosmetic hook: its error doesn't affect closing the view */ }
    })
    // A NON-ZERO EXIT IS NOT AN ERROR (see above) — `close` is the settle point.
    child.on('close', () => done(resolve))
  })
}

/**
 * (wf31/16) THE STUCK-STATE WATCHDOG'S FACTORY — fed into
 * `openReviewView({ watchdog })`.
 *
 * THE CONTRACT: returns a `stop()` that `openReviewView` calls on EVERY
 * outcome (success, error, kill) — without that the timer would stay alive
 * for the TUI's whole lifetime.
 *
 * THE THRESHOLD'S REASONING (`graceMs`): `waitForHunkSession`'s default is
 * 10 s for the ORDER GUARANTEE — there the patience is justified, because
 * starting claude is the stake. The WATCHDOG, though, has to catch the HANG,
 * and there the price of patience is the user staring at a dead terminal for
 * that long. 20 s is DOUBLE the proven wait: it's sure to let through a slow
 * (large repo, cold daemon) start, but doesn't leave it frozen for minutes.
 * NOT configurable at the call site — a per-call threshold is exactly the
 * kind of drift the next "why did it cut it off?" finding would come from.
 *
 * `probe` and `sleep`/`now` are INJECTABLE, following `waitForHunkSession`'s
 * pattern: without that the watchdog's test would take real 20 seconds.
 */
export function makeStuckViewWatchdog(repoRoot, {
  graceMs = 20_000,
  probe = probeHunkSession,
  sleep = (ms) => new Promise((r) => setTimeout(r, ms)),
  now = () => Date.now(),
} = {}) {
  return (child, onStuck) => {
    let stopped = false
    const started = now()
    const loop = async () => {
      let delay = 500
      for (;;) {
        await sleep(delay)
        if (stopped) return
        // THE CHILD IS ALREADY GONE: `close` will settle the promise anyway,
        // nothing to do here. (Either `exitCode`/`signalCode` non-null →
        // closed.)
        if (child.exitCode !== null || child.signalCode !== null) return
        const alive = probe(repoRoot)
        // SESSION FOUND → hunk is running NORMALLY, the watchdog STANDS DOWN.
        // From here the view lives as long as the user wants (`q`) — that's
        // the contract.
        if (alive === true) return
        // NOT MEASURABLE (`null`) → we do NOT kill (see the fail-soft
        // reasoning above). Keep polling: maybe the daemon recovers within
        // the grace period.
        if (alive === false && now() - started >= graceMs) {
          stopped = true
          // KILLING THE CHILD: `SIGTERM` FIRST. In the measured incident the
          // stuck hunk EXITED on this, and afterward the parent's `close`
          // handler ran cleanly (the whole chain unwound) — so `SIGKILL`
          // isn't necessary as the first step, and the gentler signal gives
          // hunk a chance to restore the terminal state (raw mode, alternate
          // screen).
          try { child.kill('SIGTERM') } catch { /* already gone */ }
          // `SIGKILL` IS THE BACKSTOP: if `SIGTERM` has no effect either, the
          // hang persists. The `unref` is load-bearing: without it this timer
          // would also delay the TUI's exit.
          const hard = setTimeout(() => {
            try { child.kill('SIGKILL') } catch { /* already gone */ }
          }, 2000)
          hard.unref?.()
          onStuck(new Error(
            'the hunk-diff view got STUCK: the session did not appear within '
            + `${Math.round(graceMs / 1000)} seconds while the hunk `
            + 'process was running — we closed the view so the terminal would '
            + 'not freeze.\n'
            + 'This is the measured error class of TTY handoff (the child and '
            + 'the TUI read the same terminal). What to do: try `d` again; if '
            + 'it recurs, open a session in a separate terminal '
            + '(`hunk diff <base>...<head>`), and the TUI will use that.',
          ))
          return
        }
        delay = Math.min(delay * 2, 2000)
      }
    }
    void loop()
    return () => { stopped = true }
  }
}

// --- node-pty relay: eliminating the SHELL FLASH on the hunk↔TUI switch ----
//
// The `script`-based path (ptyWrap/openReviewView, above) solves the THREE
// LIVE HANGS (own PTY, own process group — see `ptyWrap`'s header), but the
// ~40 ms shell flash MEASURED ON HUNK'S EXIT REMAINS: `script` only closes
// AFTER hunk dies, and in the meantime hunk's `?1049l` goes to the raw,
// inherited fd (`stdio: 'inherit'`) — the parent doesn't see it, can't hold
// it back.
//
// With node-pty, the parent IS the relay itself: the child's ENTIRE byte
// stream goes through `onData`, so the `?1049l` CAN BE FILTERED OUT BEFORE
// it reaches the real terminal — from here on WE conduct the switch, not
// hunk. So the terminal NEVER falls back to the primary buffer on hunk's
// exit: this isn't NARROWING the window, it's ELIMINATING it in principle.
//
// OPTIONAL DEPENDENCY: `node-pty` requires a native build (pnpm
// `allowBuilds` approval + a platform-specific prebuild), which isn't
// available on every machine. The caller has to work REGARDLESS of that —
// see `openReviewViaPty`'s error class.
let nodePtyCache // undefined = not tried yet; null = tried, doesn't work; otherwise the loaded module
export function resetNodePtyCache() {
  nodePtyCache = undefined
}
/**
 * RESTORING the node-pty `spawn-helper`'s EXECUTE PERMISSION — fixing an
 * UPSTREAM PACKAGING BUG AT THE POINT OF USE.
 *
 * WHAT THIS FILE IS: the TENTH argument to `pty.fork()`
 * (`node-pty/lib/unixTerminal.js`), which the native module runs INSTEAD OF
 * the target command. This is what calls `setsid()` and `TIOCSCTTY`, and then
 * `exec`s hunk — in other words, THIS is what gives the child its own session
 * and CONTROLLING TERMINAL. Exactly the property the `script -q /dev/null`
 * wrapper was also built for (see `ptyWrap`'s header), and what eliminated
 * the THREE LIVE HANGS. Not a helper program: it IS the isolation mechanism
 * itself.
 *
 * THE BUG, MEASURED (node-pty 1.1.0):
 *   - in the PUBLISHED npm tarball, the `spawn-helper`'s mode is `-rw-r--r--`
 *     (verified on the registry tarball: `tar -tvzf` → `-rw-r--r-- …
 *     prebuilds/darwin-arm64/spawn-helper`),
 *   - the `install` script (`scripts/prebuild.js`) ONLY CHECKS whether a
 *     prebuild exists — it doesn't build and doesn't chmod,
 *   - `postinstall` (`scripts/post-install.js`) cleans up `build/Release` and
 *     copies conpty on Windows — `chmod` is NOWHERE in it.
 * So the package relies ENTIRELY on tar extraction preserving the exec bit —
 * which the tarball itself doesn't carry. Symptom: `posix_spawnp failed`.
 *
 * WHY ONLY ON MACOS: the package has a prebuild ONLY for `darwin-*` and
 * `win32-*` platforms. There's none on Linux, so `node-gyp rebuild` runs
 * there, the helper is compiled LOCALLY, and ends up executable. This bug
 * does NOT affect Ubuntu CI — it affects macOS dev machines and the macOS
 * runner.
 *
 * WHY HERE, AND NOT IN A POSTINSTALL SCRIPT: core is the ONLY consumer of
 * node-pty, so fixing it in this one place takes effect in EVERY install
 * form (workspace overlay, standalone mobile/web from the vendored
 * snapshot, CI) — without having to touch three repos' install pipelines.
 * It's also SELF-HEALING: it runs again on first use after a `pnpm store
 * prune` or a fresh clone.
 *
 * FAIL-SOFT, DELIBERATELY: if the file isn't there, or the store is
 * read-only, we do NOT throw — the caller's `openReviewViaPty` falls back to
 * the `script`-based path with `NODE_PTY_UNAVAILABLE` regardless. So in the
 * worst case this fix does nothing; it cannot cause harm.
 */
function ensureSpawnHelperExecutable() {
  // No `spawn-helper` on Windows (the conpty/winpty path runs there instead)
  // — nothing to do.
  if (process.platform === 'win32') return
  let root
  try {
    root = path.dirname(createRequire(import.meta.url).resolve('node-pty/package.json'))
  } catch {
    return // not installed — the caller's fallback takes over
  }
  // THE TWO POSSIBLE LOCATIONS: the prebuild (this is the buggy branch) and
  // the locally compiled output (this one is already executable, but the
  // check is cheap and harmless).
  const candidates = [
    path.join(root, 'prebuilds', `${process.platform}-${process.arch}`, 'spawn-helper'),
    path.join(root, 'build', 'Release', 'spawn-helper'),
  ]
  for (const candidate of candidates) {
    let mode
    try {
      mode = statSync(candidate).mode
    } catch {
      continue // no helper on this branch — the other candidate can be next
    }
    try {
      accessSync(candidate, constants.X_OK)
      return // ALREADY executable: nothing to fix
    } catch { /* not executable — this is what we came to fix */ }
    try {
      // We ADD the exec bit to the EXISTING mode (`| 0o111`), not overwrite
      // it: the store's owner set the read/write permissions, we don't touch
      // those.
      chmodSync(candidate, mode | 0o111)
    } catch { /* read-only store — the caller's fallback takes over */ }
    return
  }
}

async function loadNodePty() {
  if (nodePtyCache !== undefined) return nodePtyCache
  // THE FIX RUNS BEFORE LOADING: `spawn-helper` is needed at the moment of
  // SPAWN, but `loadNodePty` is the memoized entry point — so this runs ONCE
  // per round, not on every `d` press.
  ensureSpawnHelperExecutable()
  try {
    nodePtyCache = await import('node-pty')
  } catch {
    // NOT installed, or no native build for this platform — the caller falls
    // back to the `script`-based path (see `openReviewViaPty`), NOT a loud
    // error.
    nodePtyCache = null
  }
  return nodePtyCache
}

