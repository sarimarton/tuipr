/**
 * The attestation/attribution body for ONE GitHub review (event=COMMENT).
 *
 * The intent: the review was produced locally, and the running USER verified
 * the findings. The model/tool metadata is machine-extractable
 * (parseAttribution) — inside a collapsible <details> block, so it doesn't
 * distract the PR reader.
 *
 * TWO PATHS, ONE BODY. The `tool` field carries the real provenance:
 *   - `hunk` (default): the developer wrote the findings themselves in the
 *     hunk session,
 *   - `claude-p`: the findings were generated by the `claude -p` AI review,
 *     and the developer filtered/edited them in the hunk session.
 * The PROSE follows the tool too: it used to fixedly say "made with hunk",
 * which would be a LIE for an AI review — and provenance is exactly why this
 * block exists.
 *
 * On the AI path the metadata is MEASURED, not declared: `model` comes from
 * the claude wrapper's `modelUsage` key, `costUsd` from `total_cost_usd`.
 * `findings` is ALWAYS the RETAINED (uploaded) count; `aiGenerated` is the raw
 * generated count — the difference between the two IS the human-gate metric.
 */
/**
 * THE HUNK BINARY'S PATH — FROM CORE'S OWN DEPENDENCY, not from the machine.
 *
 * WHY: `hunkdiff` is a tuipr `dependencies` entry, so the TUI BRINGS the tool
 * WITH IT — it doesn't need to be provisioned on the developer's machine
 * (neither brew nor npm -g). This function implements that binding: it
 * returns the bundled binary if it's there.
 *
 * We derive it from `CORE_ROOT`, NOT from cwd — same reasoning as in
 * `CORE_ROOT`'s docstring: the user runs the TUI from a DIFFERENT repo
 * checkout (mobile/web), where core is symlinked or an npm dependency. The
 * `node_modules/.bin` under cwd would therefore belong to the CONSUMER
 * package, where hunkdiff isn't present — the one under `CORE_ROOT`, though,
 * is always OURS.
 *
 * THE PATH FALLBACK IS DELIBERATE, and not error-swallowing: whoever installs
 * hunk for themselves (brew, npm -g, however), for them the bare `'hunk'` name
 * resolves on PATH — the old behavior is preserved byte-for-byte. And
 * `spawnFailure`'s ENOENT diagnosis still speaks up loudly if NEITHER is
 * there.
 *
 * MEMOIZED: within one TUI run the filesystem state doesn't change, but the
 * `d`/`r` path calls this many times. The cache-clearer is for the tests.
 */
let hunkBinCache
export function resetHunkBinCache() {
  hunkBinCache = undefined
}
export function hunkBin() {
  if (hunkBinCache !== undefined) return hunkBinCache
  const local = path.join(CORE_ROOT, 'node_modules', '.bin', 'hunk')
  try {
    // X_OK: mere existence isn't enough, it also has to be executable (the
    // `claudePath` uses the same yardstick).
    accessSync(local, constants.X_OK)
    hunkBinCache = local
  } catch {
    // No bundled instance (e.g. `pnpm install --prod=false`-less install, or
    // a corrupted node_modules) — we fall back to PATH.
    hunkBinCache = 'hunk'
  }
  return hunkBinCache
}

/**
 * The binary's path in a form EMBEDDABLE IN BASH (for the `script`-based PTY
 * wrapping). The absolute path can also contain spaces (e.g. a checkout under
 * "Application Support"), and there an unquoted insertion would split into
 * TWO arguments. The PATH fallback (`'hunk'`) resolves from PATH even when
 * quoted — bash semantics.
 */
export function hunkBinShell() {
  return `'${hunkBin().replaceAll("'", `'\\''`)}'`
}

export function reviewBody({ model, user, count, tool = 'hunk', aiGenerated, costUsd, sessionId, skill, aiSummary }) {
  const lead = tool === 'hunk'
    ? `Review made locally with \`hunk\` — AI-assisted analysis, findings verified by @${user}.`
    : `Review generated locally with \`claude -p\` — verified and filtered by @${user}`
      + (aiGenerated === undefined ? '' : ` (${count}/${aiGenerated} findings kept)`)
      + '.'
  const meta = { tool, model, verifiedBy: user, findings: count }
  // Only ACTUALLY measured fields go in — a `null` spend or a made-up 0 is
  // worse than the field being absent.
  if (skill !== undefined) meta.skill = skill
  if (aiGenerated !== undefined) meta.aiGenerated = aiGenerated
  if (costUsd !== undefined) meta.costUsd = costUsd
  if (sessionId !== undefined) meta.sessionId = sessionId
  // (wf24/2) THE AI SUMMARY GOES IN THE BODY TOO. The agent's verdict (what it
  // reviewed, what the main risk is) is just as useful to the PR reader as it
  // is in the TUI — and until now it appeared NOWHERE. It's included ONLY
  // when it's ACTUALLY there: an empty section is worse than its absence. The
  // `hunk` (non-AI) path stays byte-for-byte unchanged.
  const summaryBlock = typeof aiSummary === 'string' && aiSummary.trim() !== ''
    ? ['', '**AI summary:**', '', aiSummary.trim()]
    : []
  // (wf31/13) THE "This is **not** an approve: … a separate gesture."
  // SENTENCE REMOVED — the user's request, verbatim: "That not-approve
  // sentence is a silly bit of spoon-feeding, take it out."
  //
  // WHY WE LOSE NOTHING BY IT: the review's `event` is `COMMENT`, and GitHub
  // ITSELF signals the state in the review header ("commented" — not
  // "approved", not "requested changes"), without a green check or an
  // approval counter. So the sentence was explaining a fact the platform's UI
  // already states, and more strongly at that (machine state vs. a prose
  // claim). And it's not even our internal gesture-typology that concerns the
  // PR reader anyway.
  //
  // THE COUNT STAYS: `N inline comments` is real information (how much there
  // is to read through), and thanks to `comments[]`'s atomicity it's also a
  // verifiable fact.
  return [
    lead,
    ...summaryBlock,
    '',
    `${count} inline comments.`,
    '',
    '<details>',
    '<summary>Tool and model metadata</summary>',
    '',
    '```json',
    JSON.stringify(meta, null, 2),
    '```',
    '</details>',
  ].join('\n')
}

/** Reading back the reviewBody's metadata block (machine-extractability). */
export function parseAttribution(body) {
  const m = body.match(/```json\n([\s\S]*?)\n```/)
  if (!m) return null
  const meta = JSON.parse(m[1])
  return { tool: meta.tool, model: meta.model, user: meta.verifiedBy, findings: meta.findings }
}

// --- hunk session comments → GitHub review comments[] ----------------------

/**
 * Mapping findings onto the GitHub review `comments[]` shape.
 *
 * IT ACCEPTS TWO INPUT POSITION SCHEMAS, and this is NOT a convenience
 * concession — BOTH are ALIVE in the codebase, side by side:
 *
 *   (A) `{ side: 'new'|'old', line: N }` — the HUNK path's shape
 *       (`parseHunkAgentComments`: computes it from `newRange`/`oldRange`).
 *   (B) `{ newLine: N }` / `{ oldLine: N }` — the ANSWER path's shape
 *       (`hunk-findings.mjs`: the agent's response JSON uses this schema, and
 *       the review store persists it THIS way too; `aiReviewPanelLines`
 *       branches on this as well).
 *
 * A MEASURED, LIVE BUG (the user's #904 case, HTTP 422): this function only
 * knew the (A) schema. On a (B)-shaped finding, `c.line` was `undefined`, so
 * it fell onto the file-level branch — BUT GitHub didn't accept a
 * `subject_type: "file"` comment on this path, and because of `comments[]`'s
 * ATOMICITY the WHOLE review failed. The findings HAD a position (`newLine:
 * 143` and `149`), just under a DIFFERENT field name — the silent shape
 * mismatch thus turned into a 422.
 *
 * WHY WE NORMALIZE HERE, AND NOT IN THE CALLER: this is the SHARED consumer —
 * both the hunk path and the answer path (the cached review's fallback) run
 * into it here. Converting at the call sites, the next new path would fall
 * behind again and produce the same 422.
 *
 * The coordinate space MATCHES: the post-image file line number (hunk
 * `side:"new"` / `line`, or `newLine`) is exactly GitHub's `side:"RIGHT"` /
 * `line` semantics (verified empirically, see the recon report).
 *
 * WARNING: `comments[]` is ATOMIC — a single `line` that isn't in the PR's
 * diff fails the WHOLE review with a 422.
 */
export function toGithubComments(comments) {
  return comments.map((c) => {
    const body = c.rationale ? `${c.summary}\n\n${c.rationale}` : c.summary
    const pos = findingPosition(c)
    // WITHOUT A POSITION, a file-level comment (`subject_type:"file"`) —
    // with `line` it would be a 422. This is the LAST RESORT: the callers
    // (parseHunkAgentComments, normalizeAnswerFindings) already LOUDLY reject
    // a missing position, so in practice a finding only reaches here if some
    // future path skips those gates.
    if (pos === null) {
      return { path: c.filePath, subject_type: 'file', body }
    }
    return {
      path: c.filePath,
      line: pos.line,
      side: pos.side === 'old' ? 'LEFT' : 'RIGHT',
      body,
    }
  })
}

/**
 * A finding's position from WHICHEVER of the TWO accepted schemas: `{ side,
 * line }` or `null`.
 *
 * THE ORDER IS FIXED, and repeats `hunk-findings.mjs`'s doctrine: if BOTH
 * sides are given (an agent slip), the POST-IMAGE (`new`) wins — that's the
 * diff's right side, the one the reviewer reads.
 *
 * FAIL-CLOSED ON A NON-NUMBER POSITION: past the `Number.isInteger` gate,
 * only a real line number can go out. A `"143"` string or `NaN` would give a
 * 422 on GitHub, but here it becomes `null` instead, so the finding STILL
 * goes up as a file-level comment — partial loss of precision instead of a
 * silent full-review failure.
 */
function findingPosition(c) {
  // (A) schema: explicit `side` + `line`.
  if (Number.isInteger(c?.line) && c.line > 0) {
    return { side: c.side === 'old' ? 'old' : 'new', line: c.line }
  }
  // (B) schema: `newLine` / `oldLine`. The post-image comes FIRST (see above).
  if (Number.isInteger(c?.newLine) && c.newLine > 0) return { side: 'new', line: c.newLine }
  if (Number.isInteger(c?.oldLine) && c.oldLine > 0) return { side: 'old', line: c.oldLine }
  return null
}

